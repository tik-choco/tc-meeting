import { h, render } from 'preact';
import { act } from 'preact/test-utils';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { SegmentRow } from './SegmentRow';
import { translator } from '../i18n';
import { getSegmentAudio, updateSegment } from '../lib/db';
import type { Segment } from '../types';
import { getSpeechState, speak, stopSpeech } from '../lib/speech';
vi.mock('../lib/speech', () => ({ speak: vi.fn(), stopSpeech: vi.fn(), getSpeechState: vi.fn(() => ({ activeId: null, loading: false, itemIndex: null, fallback: false, error: null })) }));
vi.mock('../lib/db', () => ({ getSegmentAudio: vi.fn(), updateSegment: vi.fn() }));
vi.mock('../lib/session', () => ({ getQueue: vi.fn() }));
const retryTranslation = vi.hoisted(() => vi.fn().mockResolvedValue(undefined));
const retryProofread = vi.hoisted(() => vi.fn().mockResolvedValue(undefined));
vi.mock('../lib/assist', () => ({ getAssist: () => ({ retryTranslation, retryProofread }) }));
const segment: Segment = { id: 'm:000001', meetingId: 'm', seq: 1, startMs: 30000, endMs: 60000, status: 'done', text: 'Original text', edited: false, attempts: 1, mimeType: 'audio/webm', hasAudio: true };
let root: HTMLDivElement;
beforeEach(() => { vi.clearAllMocks(); root = document.createElement('div'); document.body.append(root); });
afterEach(() => { act(() => render(null, root)); root.remove(); vi.restoreAllMocks(); });
describe('transcript segment', () => {
  it('reads only a valid correction, including unchanged text, and updates memoized playback flags', async () => {
    const props = { segment, query: '', t: translator('en'), onError: vi.fn(), proofreadEnabled: true, language: 'en' };
    await act(() => render(h(SegmentRow, props), root));
    expect(root.querySelector('.correction-speech')).toBeNull();
    const same = { ...segment, proofread: { source: segment.text, text: segment.text, at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: same }), root));
    await act(() => root.querySelector<HTMLButtonElement>('[aria-label="Read correction aloud"]')!.click());
    expect(speak).toHaveBeenCalledWith(`seg:${segment.id}`, [segment.text], 'en');
    await act(() => render(h(SegmentRow, { ...props, segment: same, speaking: true, speechLoading: true }), root));
    expect(root.querySelector('.segment-speaking')).not.toBeNull();
    const loadingButton = root.querySelector<HTMLButtonElement>('[aria-label="Stop reading"]');
    expect(loadingButton?.getAttribute('aria-pressed')).toBe('true');
    expect(loadingButton?.getAttribute('aria-busy')).toBe('true');
    expect(loadingButton?.title).toBe('Loading voice…');
    await act(() => loadingButton!.click());
    expect(stopSpeech).toHaveBeenCalledOnce();
    await act(() => render(h(SegmentRow, { ...props, segment: { ...same, text: 'changed' } }), root));
    expect(root.querySelector('.correction-speech')).toBeNull();
    const corrected = { ...same, proofread: { ...same.proofread, text: 'Corrected text' } };
    await act(() => render(h(SegmentRow, { ...props, segment: corrected }), root));
    await act(() => root.querySelector<HTMLButtonElement>('[aria-label="Read correction aloud"]')!.click());
    expect(speak).toHaveBeenLastCalledWith(`seg:${segment.id}`, ['Corrected text'], 'en');
  });
  it('stops its own read-aloud when the row unmounts (e.g. filtered out by search), but not another owner', async () => {
    const same = { ...segment, proofread: { source: segment.text, text: segment.text, at: '2026-11-17T00:00:00Z' } };
    const props = { segment: same, query: '', t: translator('en'), onError: vi.fn(), proofreadEnabled: true, language: 'en' };
    vi.mocked(getSpeechState).mockReturnValue({ activeId: 'all:m1', loading: false, itemIndex: 0, fallback: false, error: null });
    await act(() => render(h(SegmentRow, props), root));
    act(() => render(null, root));
    expect(stopSpeech).not.toHaveBeenCalled();
    vi.mocked(getSpeechState).mockReturnValue({ activeId: `seg:${segment.id}`, loading: false, itemIndex: 0, fallback: false, error: null });
    await act(() => render(h(SegmentRow, props), root));
    act(() => render(null, root));
    expect(stopSpeech).toHaveBeenCalledOnce();    vi.mocked(getSpeechState).mockReturnValue({ activeId: null, loading: false, itemIndex: null, fallback: false, error: null });
  });
  it('saves a user edit against the latest segment without restoring deleted audio', async () => {
    const latest: Segment = { ...segment, hasAudio: false, attempts: 2, status: 'failed', error: 'stt-failed' };
    vi.mocked(updateSegment).mockImplementation(async (_id, update) => update(latest));
    await act(() => render(h(SegmentRow, { segment, query: '', t: translator('en'), onError: vi.fn() }), root));
    await act(() => { (root.querySelector('button[aria-label="Edit transcript"]') as HTMLButtonElement).click(); });
    await act(() => { const textarea = root.querySelector('textarea')!; textarea.value = 'Corrected text'; textarea.dispatchEvent(new Event('input', { bubbles: true })); });
    await act(async () => { const save = Array.from(root.querySelectorAll('button')).find(button => button.textContent === 'Save')!; save.click(); await Promise.resolve(); });
    expect(updateSegment).toHaveBeenCalledWith(segment.id, expect.any(Function));
    await expect(vi.mocked(updateSegment).mock.results[0].value).resolves.toEqual({ ...latest, text: 'Corrected text', edited: true });
  });
  it('revokes stored audio URLs when a row unmounts', async () => {
    vi.mocked(getSegmentAudio).mockResolvedValue(new Blob(['audio']));
    vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:segment');
    const revoke = vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => {});
    await act(() => render(h(SegmentRow, { segment, query: 'text', t: translator('en'), onError: vi.fn() }), root));
    expect(root.querySelector('mark')?.textContent).toBe('text');
    await act(async () => { (root.querySelector('button[aria-label="Play audio"]') as HTMLButtonElement).click(); await Promise.resolve(); });
    expect(root.querySelector('audio')?.getAttribute('src')).toBe('blob:segment');
    act(() => render(null, root));
    expect(revoke).toHaveBeenCalledWith('blob:segment');
  });
  it('shows only current translations and updates when translation fields change', async () => {
    const t = translator('en'); const onError = vi.fn();
    const props = { segment, query: 'texte', t, onError, targetLanguage: 'fr' };
    await act(() => render(h(SegmentRow, props), root));
    expect(root.textContent).toContain('Translating…');
    const translated: Segment = { ...segment, translation: { source: segment.text, lang: 'fr', text: 'Texte traduit', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: translated }), root));
    expect(root.querySelector('.segment-translation')?.getAttribute('lang')).toBe('fr');
    expect(root.querySelector('.segment-translation mark')?.textContent).toBe('Texte');
    expect(root.textContent).not.toContain('Translating…');
    await act(() => render(h(SegmentRow, { ...props, segment: { ...translated, text: 'Edited source' } }), root));
    expect(root.textContent).not.toContain('Texte traduit');
    expect(root.textContent).toContain('Translating…');
    await act(() => render(h(SegmentRow, { ...props, segment: translated, targetLanguage: 'ja' }), root));
    expect(root.textContent).not.toContain('Texte traduit');
  });
  it('retries a failed current translation and supports translation-only display', async () => {
    const t = translator('en'); const onError = vi.fn();
    const failed: Segment = { ...segment, translation: { source: segment.text, lang: 'fr', text: '', error: 'llm-failed', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { segment: failed, query: '', t, onError, targetLanguage: 'fr' }), root));
    expect(root.textContent).toContain('Translation failed.');
    await act(async () => { Array.from(root.querySelectorAll('button')).find(button => button.textContent === 'Retry translation')!.click(); await Promise.resolve(); });
    expect(retryTranslation).toHaveBeenCalledWith(segment.id);
    const translated: Segment = { ...segment, translation: { source: segment.text, lang: 'fr', text: 'Texte traduit', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { segment: translated, query: '', t, onError, targetLanguage: 'fr', translationOnly: true }), root));
    expect(root.textContent).toContain('Texte traduit');
    expect(root.textContent).not.toContain('Original text');
    expect(root.querySelector('button[aria-label="Edit transcript"]')).not.toBeNull();
  });
  it('shows a current correction, changed words and language between original and translation', async () => {
    const t = translator('en'); const onError = vi.fn();
    const props = { segment, query: 'revised', t, onError, targetLanguage: 'fr', proofreadEnabled: true, language: 'en' };
    await act(() => render(h(SegmentRow, props), root));
    expect(root.textContent).toContain('Proofreading…');
    const reserved = root.querySelector('.correction-reserve')?.textContent;
    const corrected: Segment = { ...segment, proofread: { source: segment.text, text: 'Revised text', at: '2026-11-17T00:00:00Z' }, translation: { source: segment.text, lang: 'fr', text: 'Texte traduit', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: corrected }), root));
    const correction = root.querySelector('.segment-correction')!;
    expect(correction.getAttribute('lang')).toBe('en');
    expect(correction.querySelector('.correction-reserve')?.textContent).toBe(reserved);
    expect(correction.querySelector('.correction-content')?.getAttribute('tabindex')).toBe('0');
    expect(correction.querySelector('del')?.textContent).toBe('Original');
    expect(correction.querySelector('ins mark')?.textContent).toBe('Revised');
    expect(correction.previousElementSibling?.classList.contains('transcript-text')).toBe(true);
    expect(correction.nextElementSibling?.classList.contains('segment-translation')).toBe(true);
    await act(() => render(h(SegmentRow, { ...props, segment: { ...corrected, text: 'Edited source' } }), root));
    expect(root.textContent).not.toContain('Revised');
    expect(root.textContent).toContain('Proofreading…');
    await act(() => render(h(SegmentRow, { ...props, segment: corrected, translationOnly: true }), root));
    expect(root.querySelector('.segment-correction')).toBeNull();
    expect(root.textContent).toContain('Texte traduit');
  });
  it('shows no-correction and retry states, and preserves a result when disabled', async () => {
    const props = { segment, query: '', t: translator('en'), onError: vi.fn(), proofreadEnabled: true };
    const same: Segment = { ...segment, proofread: { source: segment.text, text: segment.text, at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: same }), root));
    expect(root.querySelector('.correction-content')?.textContent).toBe('No corrections');
    await act(() => render(h(SegmentRow, { ...props, segment: { ...same, proofread: { ...same.proofread!, text: 'Original  text' } } }), root));
    expect(root.querySelector('.correction-content')?.textContent).toBe('No corrections');
    const joined: Segment = { ...segment, text: 'I have alot to say', proofread: { source: 'I have alot to say', text: 'I have a lot to say', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: joined }), root));
    expect(root.querySelector('.correction-content')?.textContent).not.toBe('No corrections');
    expect(root.querySelector('.correction-content ins')).not.toBeNull();
    const failed: Segment = { ...segment, proofread: { source: segment.text, text: '', error: 'llm-failed', at: '2026-11-17T00:00:00Z' } };
    await act(() => render(h(SegmentRow, { ...props, segment: failed }), root));
    expect(root.textContent).toContain('Proofreading failed.');
    await act(async () => { Array.from(root.querySelectorAll('button')).find(button => button.textContent === 'Retry proofreading')!.click(); await Promise.resolve(); });
    expect(retryProofread).toHaveBeenCalledWith(segment.id);
    await act(() => render(h(SegmentRow, { ...props, segment: same, proofreadEnabled: false }), root));
    expect(root.querySelector('.correction-content')?.textContent).toBe('No corrections');
    await act(() => render(h(SegmentRow, { ...props, segment, proofreadEnabled: false }), root));
    expect(root.querySelector('.segment-correction')).toBeNull();
  });
});
